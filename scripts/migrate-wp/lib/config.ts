/**
 * Media files that Gatsby already downloaded (old repo: .cache/caches/gatsby-source-wordpress).
 * Used before falling back to downloading from wewaterbackend.org.
 * Override with WP_GATSBY_CACHE=/path/to/wewater/.cache/caches/gatsby-source-wordpress.
 */
export function gatsbyCacheDir(): string | undefined {
  const candidates = [
    process.env['WP_GATSBY_CACHE'],
    path.resolve(ROOT, '../wewater/.cache/caches/gatsby-source-wordpress'),
  ].filter((p): p is string => Boolean(p));
  return candidates.find((p) => existsSync(p));
}

